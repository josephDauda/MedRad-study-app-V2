package com.example.data.supabase

import android.content.Context
import android.util.Log
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.isActive
import kotlinx.coroutines.launch
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.Response
import okhttp3.WebSocket
import okhttp3.WebSocketListener
import org.json.JSONArray
import org.json.JSONObject
import java.util.UUID
import java.util.concurrent.ConcurrentHashMap
import java.util.concurrent.atomic.AtomicInteger

/**
 * Optimized Supabase Realtime Manager for MedRad Study App.
 *
 * Architecture & Optimization Principles:
 * 1. Focuses Realtime WebSocket channels exclusively on high-value, instant signals:
 *    - "announcements": Critical departmental notices, urgent exam alerts, and schedule changes.
 *    - "app_config": Dynamic Daily CBT Sprint topic/theme updates, Mock Card session state & deadlines.
 *    - "student_feedback": Live feedback transmission for administrator review.
 * 2. Static and bulk academic content (questions, study materials, course libraries, courses, exams):
 *    - Stored directly in Supabase PostgreSQL via normal database operations (REST API).
 *    - Fetched by students on demand using ordinary database requests (REST GET) upon opening
 *      the relevant course or launching a CBT test, and cached locally in Room for offline access.
 * 3. Event Deduplication & Self-Echo Suppression:
 *    - Attaches a unique [clientId] to all outgoing broadcasts to suppress sender echo loops.
 *    - Implements a sliding-window deduplication filter ([recentEvents]) to drop duplicate events
 *      caused by simultaneous PostgreSQL CDC (postgres_changes) and manual WebSocket broadcast.
 *    - Eliminates redundant network queries and duplicate system notification banners.
 */
class SupabaseRealtimeManager(
  private val context: Context,
  private val okHttpClient: OkHttpClient,
  private val onRealtimeEvent: (table: String, eventType: String, record: JSONObject) -> Unit
) {

  private val tag = "SupabaseRealtime"
  private var webSocket: WebSocket? = null
  private val refCounter = AtomicInteger(1)
  private val scope = CoroutineScope(Dispatchers.IO)
  private var heartbeatJob: Job? = null
  private var reconnectJob: Job? = null
  private var isExplicitlyStopped = false
  var isConnected = false
    private set

  // Unique client instance identifier to suppress self-echo duplicate events
  val clientId: String = UUID.randomUUID().toString()

  // High-value realtime channels only — avoids joining unnecessary channels for static academic content
  private val tablesToListen = listOf(
    "announcements",
    "app_config",
    "student_feedback"
  )

  // Sliding-window deduplication cache (table:type:recordId -> timestamp)
  private val recentEvents = ConcurrentHashMap<String, Long>()

  fun markEventProcessed(table: String, eventType: String, recordId: String) {
    if (recordId.isNotBlank()) {
      val key = "$table:$eventType:$recordId"
      recentEvents[key] = System.currentTimeMillis()
    }
  }

  /**
   * Checks whether an event was already processed within the last 15 seconds,
   * dropping duplicates generated by concurrent CDC + Broadcast or re-deliveries.
   */
  private fun isDuplicateEvent(table: String, eventType: String, record: JSONObject): Boolean {
    val id = record.optString("id").ifBlank {
      record.optString("key").ifBlank {
        record.optString("code")
      }
    }
    val key = if (id.isNotBlank()) {
      "$table:$eventType:$id"
    } else {
      "$table:$eventType:${record.toString().hashCode()}"
    }

    val now = System.currentTimeMillis()
    val previousTime = recentEvents[key]

    // Periodically prune entries older than 30 seconds
    if (recentEvents.size > 200) {
      val iterator = recentEvents.entries.iterator()
      while (iterator.hasNext()) {
        val entry = iterator.next()
        if (now - entry.value > 30000L) {
          iterator.remove()
        }
      }
    }

    if (previousTime != null && (now - previousTime) < 15000L) {
      return true
    }

    recentEvents[key] = now
    return false
  }

  fun start() {
    if (isConnected && webSocket != null) return

    val baseUrl = SupabaseConfig.getUrl(context)
      .replace("https://", "wss://")
      .replace("http://", "ws://")
    val apiKey = SupabaseConfig.getPublishableKey(context)
    val wsUrl = "$baseUrl/realtime/v1/websocket?apikey=$apiKey&vsn=1.0.0"

    val request = Request.Builder().url(wsUrl).build()
    webSocket = okHttpClient.newWebSocket(request, object : WebSocketListener() {
      override fun onOpen(ws: WebSocket, response: Response) {
        Log.i(tag, "Supabase Realtime WebSocket connected to $baseUrl (ClientId: $clientId)")
        isConnected = true
        startHeartbeat()
        subscribeToChannels(ws)
      }

      override fun onMessage(ws: WebSocket, text: String) {
        handleIncomingMessage(text)
      }

      override fun onClosing(ws: WebSocket, code: Int, reason: String) {
        isConnected = false
        Log.w(tag, "Supabase Realtime closing: $code / $reason")
      }

      override fun onFailure(ws: WebSocket, t: Throwable, response: Response?) {
        isConnected = false
        Log.w(tag, "Supabase Realtime error: ${t.message}. Reconnecting in 5s...")
        stopHeartbeat()
        scheduleReconnect()
      }

      override fun onClosed(ws: WebSocket, code: Int, reason: String) {
        isConnected = false
        stopHeartbeat()
        scheduleReconnect()
      }
    })
  }

  private fun subscribeToChannels(ws: WebSocket) {
    for (table in tablesToListen) {
      val ref = refCounter.incrementAndGet().toString()
      val topic = "realtime:public:$table"

      val postgresChanges = JSONArray().apply {
        put(JSONObject().apply {
          put("event", "*")
          put("schema", "public")
          put("table", table)
        })
      }

      val payload = JSONObject().apply {
        put("config", JSONObject().apply {
          put("postgres_changes", postgresChanges)
        })
      }

      val joinMessage = JSONObject().apply {
        put("topic", topic)
        put("event", "phx_join")
        put("payload", payload)
        put("ref", ref)
      }

      ws.send(joinMessage.toString())
    }
  }

  private fun startHeartbeat() {
    stopHeartbeat()
    heartbeatJob = scope.launch {
      while (isActive && isConnected) {
        delay(25000L)
        val heartbeat = JSONObject().apply {
          put("topic", "phoenix")
          put("event", "heartbeat")
          put("payload", JSONObject())
          put("ref", refCounter.incrementAndGet().toString())
        }
        webSocket?.send(heartbeat.toString())
      }
    }
  }

  private fun stopHeartbeat() {
    heartbeatJob?.cancel()
    heartbeatJob = null
  }

  private fun scheduleReconnect() {
    scope.launch {
      delay(5000L)
      if (!isConnected) {
        Log.i(tag, "Attempting Supabase Realtime reconnect...")
        start()
      }
    }
  }

  /**
   * Dispatches a realtime event.
   * - Locally invokes the event callback for immediate UI updates.
   * - Transmits over WebSocket only for high-value realtime channels (announcements, app_config, student_feedback).
   * - Attaches sender_client_id to prevent self-echo loops on the originating device.
   */
  fun dispatchRealtimeEvent(table: String, eventType: String, record: JSONObject) {
    try {
      onRealtimeEvent(table, eventType, record)
    } catch (e: Exception) {
      Log.e(tag, "Error handling local realtime event callback: ${e.message}")
    }

    // Only dispatch over WebSocket for high-value realtime channels
    if (table !in tablesToListen && table != "notifications") {
      Log.d(tag, "Skipping WebSocket broadcast for non-realtime table $table (handled via standard REST database queries)")
      return
    }

    // Mark as processed locally so self-echo or CDC echo does not re-process
    val recordId = record.optString("id").ifBlank { record.optString("key") }
    if (recordId.isNotBlank()) {
      markEventProcessed(table, eventType, recordId)
    }

    scope.launch {
      try {
        if (isConnected && webSocket != null) {
          val topic = "realtime:public:$table"
          val broadcastMsg = JSONObject().apply {
            put("topic", topic)
            put("event", "broadcast")
            put("payload", JSONObject().apply {
              put("table", table)
              put("type", eventType)
              put("record", record)
              put("sender_client_id", clientId)
            })
            put("ref", refCounter.incrementAndGet().toString())
          }
          webSocket?.send(broadcastMsg.toString())
        }
      } catch (e: Exception) {
        Log.e(tag, "Error dispatching realtime event over websocket: ${e.message}")
      }
    }
  }

  internal fun handleIncomingMessage(text: String) {
    try {
      val json = JSONObject(text)
      val event = json.optString("event")
      val topic = json.optString("topic")

      if (event == "postgres_changes" || event == "broadcast") {
        val payload = json.optJSONObject("payload") ?: return

        // 1. Check sender client ID to prevent self-echo loops on the sending device
        val senderClientId = payload.optString("sender_client_id")
        if (senderClientId.isNotBlank() && senderClientId == clientId) {
          Log.d(tag, "Ignored self-echo event from current client")
          return
        }

        val data = payload.optJSONObject("data") ?: payload
        var table = data.optString("table")
        if (table.isBlank() && topic.startsWith("realtime:public:")) {
          table = topic.substringAfterLast(":")
        }
        val type = data.optString("type", if (event == "broadcast") "UPDATE" else "UNKNOWN")
        val record = data.optJSONObject("record")
          ?: payload.optJSONObject("record")
          ?: data.optJSONObject("old_record")
          ?: payload.optJSONObject("old_record")
          ?: data

        if (table.isNotBlank()) {
          // 2. Filter duplicate events (e.g. received via both postgres_changes and broadcast)
          if (isDuplicateEvent(table, type, record)) {
            Log.d(tag, "Suppressed duplicate realtime event on $table ($type)")
            return
          }
          onRealtimeEvent(table, type, record)
        }
      }
    } catch (e: Exception) {
      Log.e(tag, "Error parsing realtime message: ${e.message}")
    }
  }

  fun stop() {
    stopHeartbeat()
    webSocket?.close(1000, "App paused or destroyed")
    webSocket = null
    isConnected = false
  }
}
